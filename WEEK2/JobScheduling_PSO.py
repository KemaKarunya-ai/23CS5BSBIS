import numpy as np

# ==========================================
# STEP 1: DEFINE THE PROBLEM (MANUAL INPUT)
# ==========================================
print("--- Job Scheduling PSO Setup ---")
num_jobs = int(input("Enter the total number of Jobs: "))
num_machines = int(input("Enter the total number of Machines: "))

print(f"\nEnter the processing times row by row.")
print(f"For each job, type {num_machines} space-separated numbers (e.g., '4 7 6') and press Enter:\n")

matrix_list = []
for i in range(num_jobs):
    while True:
        try:
            row_input = input(f"Job {i} processing times: ")
            row_values = [float(x) for x in row_input.split()]
            if len(row_values) != num_machines:
                print(f"Error: You must enter exactly {num_machines} values. Try again.")
                continue
            matrix_list.append(row_values)
            break
        except ValueError:
            print("Error: Invalid numbers. Please enter numbers only separated by spaces.")

processing_times = np.array(matrix_list)

def compute_fitness(position):
    """
    Evaluates the quality of a schedule (position vector).
    Converts continuous values to machine indices and finds the makespan.
    Goal: MINIMIZE this value.
    """
    assignments = np.clip(np.round(position), 0, num_machines - 1).astype(int)
    
    machine_loads = np.zeros(num_machines)
    for job_idx, machine_idx in enumerate(assignments):
        machine_loads[machine_idx] += processing_times[job_idx, machine_idx]
        
    makespan = np.max(machine_loads)
    return makespan, assignments

# ==========================================
# STEP 2: INITIALIZE PARAMETERS
# ==========================================
num_particles = 35
max_iterations = 150
w = 0.75    # Inertia weight
c1 = 1.6    # Cognitive coefficient
c2 = 1.6    # Social coefficient

# ==========================================
# STEP 3: INITIALIZE PARTICLES
# ==========================================
particle_positions = np.random.uniform(0, num_machines - 1, (num_particles, num_jobs))
particle_velocities = np.random.uniform(-1, 1, (num_particles, num_jobs))

personal_best_positions = np.copy(particle_positions)
personal_best_fitness = np.full(num_particles, np.inf)

global_best_position = None
global_best_fitness = np.inf
global_best_schedule = None

# ==========================================
# STEPS 4, 5 & 6: EVALUATE, UPDATE, ITERATE
# ==========================================
print("\nOptimizing schedule... Please wait...")

for iteration in range(max_iterations):
    for i in range(num_particles):
        
        current_fitness, current_schedule = compute_fitness(particle_positions[i])
        
        if current_fitness < personal_best_fitness[i]:
            personal_best_fitness[i] = current_fitness
            personal_best_positions[i] = np.copy(particle_positions[i])
            
        if current_fitness < global_best_fitness:
            global_best_fitness = current_fitness
            global_best_position = np.copy(particle_positions[i])
            global_best_schedule = current_schedule
            
    r1 = np.random.rand(num_particles, num_jobs)
    r2 = np.random.rand(num_particles, num_jobs)
    
    particle_velocities = (w * particle_velocities + 
                           c1 * r1 * (personal_best_positions - particle_positions) + 
                           c2 * r2 * (global_best_position - particle_positions))
    
    particle_positions += particle_velocities
    particle_positions = np.clip(particle_positions, 0, num_machines - 1)

# ==========================================
# STEP 7: OUTPUT THE BEST SOLUTION
# ==========================================
print("\n" + "=" * 60)
print("OPTIMAL JOB SCHEDULE GENERATED BY PSO")
print("=" * 60)
print(f"Optimal Execution Time (Makespan): {global_best_fitness} time units\n")

print("Job-to-Machine Allocations:")
for job, machine in enumerate(global_best_schedule):
    duration = processing_times[job, machine]
    print(f"  - Job {job} -> Assigned to Machine {machine} (Duration: {duration})")

machine_workloads = np.zeros(num_machines)
for job, machine in enumerate(global_best_schedule):
    machine_workloads[machine] += processing_times[job, machine]

print("\nFinal Load Balance Across Machines:")
for machine_id, load in enumerate(machine_workloads):
    print(f"  - Machine {machine_id}: Total Processing Load = {load}")
print("=" * 60)
 
